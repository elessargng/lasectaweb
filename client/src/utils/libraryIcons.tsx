/** Icono por defecto cuando la carpeta no tiene ninguno asignado o el guardado ya no existe. */
export const DEFAULT_LIBRARY_ICON: LucideIcon = Folder;

export function getLibraryIcon(name?: string | null): LucideIcon {
  if (!name) return DEFAULT_LIBRARY_ICON;
  return LIBRARY_ICONS[name] || DEFAULT_LIBRARY_ICON;
}
