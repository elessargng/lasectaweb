const escapar = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

// Los más largos antes («Hell's Librarian» antes que «Librarian»), como palabras enteras
const NOMBRES = Object.keys(FONETICA).sort((a, b) => b.length - a.length);
const PATRON = new RegExp(`(?<![\\p{L}'’])(${NOMBRES.map(escapar).join('|')})(?![\\p{L}])`, 'gu');

/** La frase como debe sonar: los nombres ingleses de los personajes, escritos como se pronuncian en español. */
export const paraLaVoz = (texto: string): string => texto.replace(/’/g, "'").replace(PATRON, (nombre) => FONETICA[nombre] ?? nombre);
